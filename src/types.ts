export enum IssueCategory {
  WATER_LEAK = "Water leak",
  NO_SUPPLY = "No water supply",
  DIRTY_WATER = "Dirty water",
  LOW_PRESSURE = "Low pressure",
  TANKER_DELAY = "Tanker delay",
  ROAD_POTHOLE = "Road pothole",
  DRAINAGE_BLOCKAGE = "Drainage blockage",
  STREETLIGHT_ISSUE = "Streetlight issue",
  GARBAGE_ISSUE = "Garbage issue",
  OTHER = "Other"
}

export enum ComplaintStatus {
  SUBMITTED = "submitted",
  ASSIGNED = "assigned",
  IN_PROGRESS = "in progress",
  PROOF_UPLOADED = "proof uploaded",
  PENDING_VERIFICATION = "pending citizen verification",
  CLOSED = "closed",
  REOPENED = "reopened"
}

export interface Complaint {
  id: string;
  userId: string;
  userName: string;
  phoneNumber: string;
  email?: string;
  selectedLanguage: "en" | "hi" | "ta" | "te";
  issueCategory: IssueCategory;
  description: string;
  voiceTranscription?: string;
  voiceAudioUrl?: string; // or base64 representation
  complaintPhoto: string; // base64 data URL
  repairPhoto?: string; // base64 data URL
  latitude: number;
  longitude: number;
  address: string;
  ward: string;
  assignedOfficialId: string;
  assignedDepartment: string;
  urgencyScore: "Low" | "Medium" | "High";
  status: ComplaintStatus;
  createdTime: string;
  updatedTime: string;
  citizenVerificationStatus: "pending" | "approved" | "rejected";
  officerVerificationStatus: "pending" | "completed";
  geoConsistencyDistance?: number; // Distance in meters between complaint & repair photo
  geoConsistencyVerified?: boolean;
  officerLatitude?: number;
  officerLongitude?: number;
}

export interface Official {
  id: string;
  name: string;
  email: string;
  mobileNumber: string;
  officeHours: string;
  ward: string;
  department: string;
  escalationOfficer: string;
  activeStatus: boolean;
}

export interface UserSession {
  userId: string;
  role: "citizen" | "official";
  phoneNumber: string;
  name: string;
  email?: string;
  ward?: string; // if official
  officialId?: string; // if official
  language: "en" | "hi" | "ta" | "te";
}

